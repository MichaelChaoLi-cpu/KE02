from __future__ import annotations

import pandas as pd
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]  # project root

src = ROOT / "data/exp/data-preprocessing/staging/claim_sensitivity.parquet"
dst = ROOT / "data/processed/repeated_shock_claim_sensitivity_preprocessed.parquet"

# --- Load ---
df = pd.read_parquet(src)

# --- Select and rename columns ---
rename_map = {
    "Claim ID": "Claim ID",
    "Claim": "Claim",
    "Sensitivity Dimension": "Sensitivity Dimension",
    "Scenario": "Scenario",
    "Result": "Result",
    "Classification": "Classification",
    "Evidence": "Evidence",
    "Inference Ceiling": "Inference Ceiling",
}
df = df[list(rename_map.keys())].rename(columns=rename_map)

# --- Variable-level preprocessing ---
# Claim ID
df["Claim ID"] = df["Claim ID"].str.strip()
# Claim
df["Claim"] = df["Claim"].str.strip()
# Sensitivity Dimension
df["Sensitivity Dimension"] = df["Sensitivity Dimension"].str.strip()
# Scenario
df["Scenario"] = df["Scenario"].str.strip()
# Result
df["Result"] = df["Result"].str.strip()
# Classification
df["Classification"] = df["Classification"].str.strip()
# Evidence
df["Evidence"] = df["Evidence"].str.strip()
# Inference Ceiling
df["Inference Ceiling"] = df["Inference Ceiling"].str.strip()

# --- Save ---
dst.parent.mkdir(parents=True, exist_ok=True)
df.to_parquet(dst, index=False, engine="pyarrow")
print(f"Saved {len(df):,} rows × {len(df.columns)} cols → {dst.relative_to(ROOT)}")
