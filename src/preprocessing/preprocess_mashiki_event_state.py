#!/usr/bin/env python3
"""Preprocessing script for data/exp/data-preprocessing/staging/mashiki_event_state.parquet
Output: data/processed/mashiki_repeated_shock_event_state_preprocessed.parquet

Generated by data-preprocessing skill.
"""
from __future__ import annotations

import pandas as pd
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]  # project root

src = ROOT / "data/exp/data-preprocessing/staging/mashiki_event_state.parquet"
dst = ROOT / "data/processed/mashiki_repeated_shock_event_state_preprocessed.parquet"

# --- Load ---
df = pd.read_parquet(src)

# --- Select and rename columns ---
rename_map = {
    "Case ID": "Case ID",
    "Event": "Event",
    "Observation Time": "Observation Time",
    "Subsegment": "Subsegment",
    "Observation Type": "Observation Type",
    "Observation State": "Observation State",
    "Measurement System": "Measurement System",
    "Passage Layer Available": "Passage Layer Available",
    "Observed Corridor Passage": "Observed Corridor Passage",
    "Unique Corridor Traces": "Unique Corridor Traces",
    "Longitudinal Coverage Proxy": "Longitudinal Coverage Proxy",
    "Elapsed Hours Since Event": "Elapsed Hours Since Event",
    "Event-Time Bound": "Event-Time Bound",
    "MMI Mean": "MMI Mean",
    "PGA Mean (g)": "PGA Mean (g)",
    "Source SHA-256": "Source SHA-256",
    "Interpretation": "Interpretation",
}
df = df[list(rename_map.keys())].rename(columns=rename_map)

# --- Variable-level preprocessing ---
# Case ID
df["Case ID"] = df["Case ID"].str.strip()
# Event
df["Event"] = df["Event"].str.strip()
# Observation Time
df["Observation Time"] = pd.to_datetime(df["Observation Time"], errors="coerce")
# Subsegment
df["Subsegment"] = df["Subsegment"].str.strip()
# Observation Type
df["Observation Type"] = df["Observation Type"].str.strip()
# Observation State
df["Observation State"] = df["Observation State"].str.strip()
# Measurement System
df["Measurement System"] = df["Measurement System"].str.strip()
# Passage Layer Available
_boolean_map_Passage_Layer_Available = {True: True, False: False, "True": True, "False": False, "true": True, "false": False, 1: True, 0: False}
df["Passage Layer Available"] = df["Passage Layer Available"].map(_boolean_map_Passage_Layer_Available).astype("boolean")
# Observed Corridor Passage
_boolean_map_Observed_Corridor_Passage = {True: True, False: False, "True": True, "False": False, "true": True, "false": False, 1: True, 0: False}
df["Observed Corridor Passage"] = df["Observed Corridor Passage"].map(_boolean_map_Observed_Corridor_Passage).astype("boolean")
# Unique Corridor Traces
df["Unique Corridor Traces"] = pd.to_numeric(df["Unique Corridor Traces"], errors="coerce")
# Longitudinal Coverage Proxy
df["Longitudinal Coverage Proxy"] = pd.to_numeric(df["Longitudinal Coverage Proxy"], errors="coerce")
# Elapsed Hours Since Event
df["Elapsed Hours Since Event"] = pd.to_numeric(df["Elapsed Hours Since Event"], errors="coerce")
# Event-Time Bound
df["Event-Time Bound"] = df["Event-Time Bound"].str.strip()
# MMI Mean
df["MMI Mean"] = pd.to_numeric(df["MMI Mean"], errors="coerce")
# PGA Mean (g)
df["PGA Mean (g)"] = pd.to_numeric(df["PGA Mean (g)"], errors="coerce")
# Source SHA-256
df["Source SHA-256"] = df["Source SHA-256"].str.strip()
# Interpretation
df["Interpretation"] = df["Interpretation"].str.strip()

# --- Save ---
dst.parent.mkdir(parents=True, exist_ok=True)
df.to_parquet(dst, index=False, engine="pyarrow")
print(f"Saved {len(df):,} rows × {len(df.columns)} cols → {dst.relative_to(ROOT)}")
